//! #2647: what a press finds in and around inline elements' padding, as
//! Chrome 157's `elementFromPoint` finds it (follow-ups to #2618).
//!
//! 1. An inline element's padding past its block's box: the line is near
//!    the box's edge and the padding reaches out of it (`big`, `an`). The hit
//!    test stopped at the block's box, so the point found the body.
//! 2. A `pointer-events: none` element's padding passes the point to the
//!    element around it only where that one's box holds it (`pn2` in `a2`):
//!    above and below `a2`'s box it is the block's. The walk went to the
//!    parent wherever the point was.
//! 3. A link holding only an image is found in its padding around it (`a3`).
//!    Elements with a padding and no background were gathered only from the
//!    text they hold, and this one holds none.
//! 4. Nested elements (`n4` in `o4`): the inner one over its glyphs, and a
//!    `visibility: hidden` one's text passes the point to the one around it
//!    (`h4`); two mutants of the walk survived the old tests.
//!
//! The scene, set in Inter on both sides; Chrome 157 headless at 1x, the same
//! body under `@font-face { font-family: ProbeFace; src: url(Inter-Regular.ttf) }`.
//! Each row is `elementFromPoint` at `x = 1, 3, … 199`: `.` the body, a
//! digit or letter the element of `SYMBOLS`, `?` a point whose neighbours
