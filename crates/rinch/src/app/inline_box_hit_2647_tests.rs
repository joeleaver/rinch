fn document() -> rinch_dom::RinchDocument {
    use parley::fontique::{Blob, FontInfoOverride};
    let mut doc = rinch_dom::RinchDocument::new();
    let registered = doc.font_cx.collection.register_fonts(
        Blob::new(std::sync::Arc::new(FACE)),
        Some(FontInfoOverride {
            family_name: Some("ProbeFace"),
            ..Default::default()
        }),
    );
    assert_eq!(registered.len(), 1, "one file, one family");
    doc.load_css(CSS);
    let b = doc.body();
    doc.set_inner_html(b, BODY);
    doc.resolve_layout(300.0, 320.0);
    doc
}

/// The element a press at `(x, y)` is delivered to, from the hit up, as the
/// click path starts its walk: its `id`, or `None` (the body).
fn pressed(doc: &rinch_dom::RinchDocument, x: f32, y: f32) -> Option<String> {
    let tree = &doc.tree;
    let hit = hit_test(tree, x, y)?;
    let mut at = event_target_at(tree, hit, x, y).unwrap_or(hit);
    if tree.get(at)?.is_text() {
        at = tree.get(at)?.parent?;
    }
    doc.get_attribute(NodeId(at), "id")
}

/// Every compared point lands where Chrome's lands.
#[test]
fn a_press_in_and_around_inline_padding_lands_where_chromes_does() {
    let doc = document();
    let mut bad = Vec::new();
    let mut compared = 0;
    for &(y, row) in ROWS {
        for (i, c) in row.chars().enumerate() {
            if c == '?' {
                continue;
            }
            let want = SYMBOLS.iter().find(|s| s.0 == c).map(|s| s.1);
            let x = 1.0 + 2.0 * i as f32;
            let got = pressed(&doc, x, y as f32);
            compared += 1;
            if got.as_deref() != want {
                bad.push(format!("({x}, {y}): {got:?}, Chrome {want:?}"));
            }
        }
    }
    assert!(compared > 5000, "{compared} points compared");
    assert!(
        bad.is_empty(),
        "{} of {compared} points:\n{}",
        bad.len(),
        bad.join("\n")
    );
}
